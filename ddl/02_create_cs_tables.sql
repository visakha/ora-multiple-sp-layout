-- C_S_* landing tables (ORA-multiple-SP-layout install DDL).
-- Translated from the v3 unified CREATE files (Snowflake) with the
-- mirror type rules: VARCHAR -> VARCHAR2(4000) [or (n) if given],
-- NUMBER(38,0) -> NUMBER(38), TIMESTAMP_NTZ -> TIMESTAMP,
-- BOOLEAN -> NUMBER(1).
-- V1-FAITHFUL SHAPE: the v3 flag columns (SPINE_FILTERED_YN,
-- SPINE_FILTER_REASON, NONSPINE_FILTERED_YN, NONSPINE_FILTER_REASON)
-- and all DIAG_* columns are OMITTED here — v1 procedures never write
-- them. The column set is otherwise the v3 unified superset (union
-- across sources), which is a superset of every single-source v1 table.
-- All columns are NULLABLE and there are no PK/UK/NOT NULL constraints:
-- install DDL is intentionally constraint-free; the estate's real
-- constraints live in the source database.
-- NO DROP STATEMENTS IN THIS FILE. Teardown lives in drop_all.sql only.

